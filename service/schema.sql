CREATE TABLE IF NOT EXISTS members (
 email TEXT PRIMARY KEY,
 verified INTEGER NOT NULL DEFAULT 0,
 version INTEGER NOT NULL DEFAULT 1
);
CREATE TABLE IF NOT EXISTS subscriptions (
 email TEXT NOT NULL REFERENCES members(email) ON DELETE CASCADE,
 market TEXT NOT NULL,
 PRIMARY KEY(email, market)
);
CREATE TABLE IF NOT EXISTS tokens (
 hash TEXT PRIMARY KEY,
 email TEXT NOT NULL,
 markets TEXT NOT NULL,
 expires INTEGER NOT NULL
);
CREATE INDEX IF NOT EXISTS tokens_expiry ON tokens(expires);
CREATE TABLE IF NOT EXISTS rates (key TEXT PRIMARY KEY, count INTEGER NOT NULL, expires INTEGER NOT NULL);
CREATE TABLE IF NOT EXISTS charts (market TEXT PRIMARY KEY, date TEXT NOT NULL);
CREATE TABLE IF NOT EXISTS outbox (
 id TEXT PRIMARY KEY,
 email TEXT NOT NULL,
 subject TEXT NOT NULL,
 text TEXT NOT NULL,
 created INTEGER NOT NULL,
 lease INTEGER NOT NULL DEFAULT 0,
 sent INTEGER NOT NULL DEFAULT 0
);
CREATE INDEX IF NOT EXISTS outbox_pending ON outbox(sent, created);
